"""Маскирование PII для логов (инвариант 8): телефоны и email."""

import re

_EMAIL = re.compile(r"[\w.+-]+@[\w-]+(?:\.[\w-]+)+")
# Российские номера (+7/8 и 10 цифр) и международные (+код, 10+ цифр) с любыми разделителями.
# Цены («89 990 ₽») и номера заказов (5–6 цифр) под шаблоны не попадают.
_PHONE = re.compile(
    r"(?<!\w)(?:\+7|8)[\s\-()]*\d{3}[\s\-()]*\d{3}[\s\-]*\d{2}[\s\-]*\d{2}(?!\d)"
    r"|(?<!\w)\+\d[\d\s\-()]{8,}\d(?!\d)"
)


def mask_pii(text: str) -> str:
    return _PHONE.sub("[телефон]", _EMAIL.sub("[email]", text))
